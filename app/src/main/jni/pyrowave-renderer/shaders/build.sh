#!/bin/sh
# Regenerates ../shaders_spv.h from the GLSL sources with the NDK's glslc.
# The SPIR-V is committed so the app build needs no shader compiler.
#
#   ANDROID_NDK=/path/to/ndk sh build.sh
set -e
cd "$(dirname "$0")"

GLSLC="$(ls "$ANDROID_NDK"/shader-tools/*/glslc* | head -n 1)"
OUT=../shaders_spv.h

emit() {
    # $1: source file, $2: C array name
    "$GLSLC" -O --target-env=vulkan1.1 -mfmt=num -o "$1.inc" "$1"
    {
        echo "static const uint32_t $2[] = {"
        cat "$1.inc"
        echo "};"
        echo
    } >> "$OUT"
    rm "$1.inc"
}

{
    echo "// Generated by shaders/build.sh from fullscreen.vert and planar_csc.frag. Do not edit."
    echo "#pragma once"
    echo
    echo "#include <stdint.h>"
    echo
} > "$OUT"

emit fullscreen.vert k_FullscreenVertSpv
emit planar_csc.frag k_PlanarCscFragSpv
